import chokidar from 'chokidar';
import { execFileSync } from 'node:child_process';
import { writeFileSync, rmSync } from 'node:fs';
const REPO = '/Users/wharsojo/agentic-ai/deepseek-insight';
const TARGET = REPO + '/.git/index';
const w = chokidar.watch(TARGET, { ignoreInitial: true, awaitWriteFinish: { stabilityThreshold: 50, pollInterval: 25 } });
const events = [];
w.on('add', (p) => events.push('add ' + p));
w.on('change', (p) => events.push('change ' + p));
w.on('unlink', (p) => events.push('unlink ' + p));
w.on('error', (e) => events.push('error ' + e.message));
w.on('ready', () => console.log('watcher ready, watching:', w.getWatched()));
await new Promise((r) => setTimeout(r, 1000));
writeFileSync(REPO + '/_pulse-chok.txt', 'x\n');
execFileSync('git', ['-C', REPO, 'add', '_pulse-chok.txt']);
console.log('git add done at', new Date().toISOString());
await new Promise((r) => setTimeout(r, 5000));
console.log('events:', JSON.stringify(events, null, 1));
rmSync(REPO + '/_pulse-chok.txt', { force: true });
execFileSync('git', ['-C', REPO, 'reset', '-q', '--', '_pulse-chok.txt']);
await w.close();
process.exit(0);